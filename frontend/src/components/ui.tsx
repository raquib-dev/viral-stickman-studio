  failed: { icon: "✕", label: "failed", color: "var(--critical)" },
  waiting_gate: { icon: "⏸", label: "needs you", color: "var(--serious)" },
  cancelled: { icon: "–", label: "cancelled", color: "var(--text-muted)" },
  interrupted: { icon: "!", label: "interrupted", color: "var(--serious)" },
  stale: { icon: "↻", label: "stale", color: "var(--serious)" },
  stopped: { icon: "■", label: "stopped", color: "var(--text-muted)" },
  rejected: { icon: "✕", label: "rejected", color: "var(--critical)" },
  idle: { icon: "○", label: "idle", color: "var(--text-muted)" },
