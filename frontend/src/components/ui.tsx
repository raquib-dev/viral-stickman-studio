export function Tabs<T extends string>({ tabs, value, onChange }: { tabs: { id: T; label: string }[]; value: T; onChange: (v: T) => void }) {
  return (
    <div className="inline-flex rounded-lg border border-line bg-surface-2 p-0.5" role="tablist">
      {tabs.map((t) => (
        <button key={t.id} role="tab" aria-selected={value === t.id} onClick={() => onChange(t.id)}
          className={`rounded-md px-2.5 py-1 text-xs font-medium ${value === t.id ? "bg-surface text-ink shadow-sm" : "text-ink-3 hover:text-ink"}`}>
          {t.label}
        </button>
      ))}
    </div>
  );
}

export const fmtUsd = (n: number | null | undefined) => `$${(n ?? 0).toFixed(2)}`;
export const fmtTime = (s: number) => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, "0")}`;

export function fmtDur(sec: number | null | undefined): string {
  if (sec == null || !isFinite(sec) || sec < 0) return "—";
  if (sec < 60) return `${Math.round(sec)}s`;
  const m = Math.floor(sec / 60), s = Math.round(sec % 60);
  return m < 60 ? `${m}m ${String(s).padStart(2, "0")}s` : `${Math.floor(m / 60)}h ${m % 60}m`;
}
