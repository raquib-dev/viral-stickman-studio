export function StatusChip({ status, small }: { status: StageStatus | string; small?: boolean }) {
  const s = STATUS[status] ?? { icon: "?", label: status, color: "var(--text-muted)" };
  return (
    <span className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full border border-line bg-surface-2 ${small ? "px-1.5 py-0 text-[11px]" : "px-2 py-0.5 text-xs"} font-medium text-ink-2`}
      data-status={status}>
      <span aria-hidden style={{ color: s.color }} className={status === "running" ? "animate-pulse" : ""}>{s.icon}</span>
      {s.label}
    </span>
  );
}

export function ProgressBar({ value, label }: { value: number; label?: string }) {
  const pct = Math.round(Math.max(0, Math.min(1, value)) * 100);
  return (
    <div className="w-full" title={label ?? `${pct}%`} role="progressbar" aria-valuenow={pct} aria-valuemin={0} aria-valuemax={100}>
      <div className="h-1.5 w-full overflow-hidden rounded-full bg-surface-3">
        <div className="h-full rounded-full bg-accent transition-all" style={{ width: `${pct}%` }} />
      </div>
    </div>
  );
}

export function CopyButton({ text, label = "Copy" }: { text: string; label?: string }) {
  const [done, setDone] = useState(false);
  return (
    <button className="btn !px-2 !py-1 text-xs" onClick={async () => {
      try { await navigator.clipboard.writeText(text); } catch {
        const ta = document.createElement("textarea"); ta.value = text; document.body.appendChild(ta); ta.select();
        document.execCommand("copy"); ta.remove();
      }
      setDone(true); setTimeout(() => setDone(false), 1400);
    }}>{done ? "✓ Copied" : label}</button>
  );
}

